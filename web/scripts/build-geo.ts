// Pre-project Natural Earth land (world-atlas, public domain) into StormCheck map space so the
// client never ships a world atlas. usage: npx tsx scripts/build-geo.ts
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { feature, mesh } from "topojson-client";
import { geoPath, geoProjection, geoGraticule } from "d3-geo";
import type { Topology, GeometryCollection } from "topojson-specification";
import { K } from "../src/lib/geo";

const atlas = (name: string) =>
  JSON.parse(readFileSync(join(process.cwd(), "node_modules/world-atlas", name), "utf8")) as Topology;

// Raw projection works in radians; scale(180/π) puts output in degrees·K, and d3 flips y.
const projection = geoProjection((l: number, p: number) => [l * K, p])
  .scale(180 / Math.PI)
  .translate([0, 0])
  .precision(0.05);

const clipTo = (lonMin: number, lonMax: number, latMin: number, latMax: number) =>
  projection.clipExtent([
    [lonMin * K, -latMax],
    [lonMax * K, -latMin],
  ]);

/** Land as filled polygons (the route map). Clipping adds edges along the box, so the box must sit outside the view. */
function landPath(file: string, lonMin: number, lonMax: number, latMin: number, latMax: number) {
  const topo = atlas(file);
  return geoPath(clipTo(lonMin, lonMax, latMin, latMax)).digits(3)(feature(topo, topo.objects.land as GeometryCollection)) ?? "";
}

/** The coastline as lines (the hero): clipped lines just stop at the box, with no edges along it. */
function coastPath(file: string, lonMin: number, lonMax: number, latMin: number, latMax: number) {
  const topo = atlas(file);
  return geoPath(clipTo(lonMin, lonMax, latMin, latMax)).digits(3)(mesh(topo, topo.objects.land as GeometryCollection)) ?? "";
}

/** Douglas–Peucker on each ring or line of a projected path. eps is in map units (≈ degrees) and may vary by place. */
function simplify(d: string, eps: number | ((x: number, y: number) => number), digits: number) {
  const tol = typeof eps === "number" ? () => eps : eps;
  const out: string[] = [];
  for (const part of d.split("M").filter(Boolean)) {
    const closed = part.endsWith("Z");
    const pts = (closed ? part.slice(0, -1) : part).split("L").map((xy) => xy.split(",").map(Number) as [number, number]);
    const keep = new Uint8Array(pts.length);
    keep[0] = keep[pts.length - 1] = 1;
    const todo: [number, number][] = [[0, pts.length - 1]];
    while (todo.length) {
      const [a, b] = todo.pop()!;
      const [ax, ay] = pts[a];
      const [bx, by] = pts[b];
      const dx = bx - ax;
      const dy = by - ay;
      const len = Math.hypot(dx, dy);
      let far = -1;
      let max = 0;
      for (let i = a + 1; i < b; i++) {
        const [px, py] = pts[i];
        const dist = len < 1e-9 ? Math.hypot(px - ax, py - ay) : Math.abs(dy * px - dx * py + bx * ay - by * ax) / len;
        if (dist > max) [max, far] = [dist, i];
      }
      if (far > 0 && max > tol(...pts[far])) {
        keep[far] = 1;
        todo.push([a, far], [far, b]);
      }
    }
    const kept = pts.filter((_, i) => keep[i]);
    const xs = kept.map((q) => q[0]);
    const ys = kept.map((q) => q[1]);
    // islets and stubs smaller than the tolerance would only be dots
    if (Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys)) < 2 * tol(...kept[0])) continue;
    out.push("M" + kept.map(([x, y]) => `${+x.toFixed(digits)},${+y.toFixed(digits)}`).join("L") + (closed ? "Z" : ""));
  }
  return out.join("");
}

const out = join(process.cwd(), "src/data/geo");
mkdirSync(out, { recursive: true });

// The route map: the North Atlantic as a card (~0.1 map units per pixel), so 0.08 is under a pixel.
const atlantic = simplify(landPath("land-50m.json", -130, 45, 15, 80), 0.08, 2);
// The hero and the film. The box covers their widest view, even on a tall phone. The closing view over
// Ireland is ~0.004 units per pixel, so 10m data at 0.006 there; elsewhere only the wide opening view
// shows it, and 0.025 is about a pixel.
const nearDublin = (x: number, y: number) => x > -15 * K && x < 0 && y > -62 && y < -46;
const coast = simplify(coastPath("land-10m.json", -28, 9, 31, 75), (x, y) => (nearDublin(x, y) ? 0.006 : 0.025), 3);

projection.clipExtent(null);
const grat = geoGraticule().extent([
  [-130, 15],
  [45, 81],
]).step([10, 10]);
const graticule = geoPath(projection).digits(2)(grat()) ?? "";

// Two modules, so a route only downloads the map it draws (bundlers don't split one module's exports by route).
const header = `// Generated by scripts/build-geo.ts from Natural Earth (world-atlas). Do not edit.\n`;
writeFileSync(join(out, "land.ts"), header + `export const LAND_ATLANTIC = ${JSON.stringify(atlantic)};\n`);
writeFileSync(join(out, "coast.ts"), header + `export const COAST_NEAR = ${JSON.stringify(coast)};\nexport const GRATICULE = ${JSON.stringify(graticule)};\n`);
console.log("atlantic", (atlantic.length / 1024).toFixed(0), "KB · coast", (coast.length / 1024).toFixed(0), "KB · graticule", (graticule.length / 1024).toFixed(1), "KB");
