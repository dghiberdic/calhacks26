// Pre-project Natural Earth land (world-atlas, public domain) into StormCheck map space so the
// client never ships a world atlas. usage: npx tsx scripts/build-geo.ts
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { feature } from "topojson-client";
import { geoPath, geoProjection, geoGraticule } from "d3-geo";
import type { Topology, GeometryCollection } from "topojson-specification";
import { K } from "../src/lib/geo";

const atlas = (name: string) =>
  JSON.parse(readFileSync(join(process.cwd(), "node_modules/world-atlas", name), "utf8")) as Topology;

// Raw projection works in radians; scale(180/π) puts output in degrees·K, and d3 flips y.
const projection = geoProjection((l: number, p: number) => [l * K, p])
  .scale(180 / Math.PI)
  .translate([0, 0])
  .precision(0.05);

function landPath(file: string, lonMin: number, lonMax: number, latMin: number, latMax: number) {
  const topo = atlas(file);
  const land = feature(topo, topo.objects.land as GeometryCollection);
  const [x0, y0] = [lonMin * K, -latMax];
  const [x1, y1] = [lonMax * K, -latMin];
  const p = projection.clipExtent([
    [x0, y0],
    [x1, y1],
  ]);
  const path = geoPath(p).digits(2);
  return path(land) ?? "";
}

const out = join(process.cwd(), "src/data/geo");
mkdirSync(out, { recursive: true });

const atlantic = landPath("land-50m.json", -130, 45, 15, 80);
const isles = landPath("land-10m.json", -11.5, 2.5, 49.5, 59.5);

projection.clipExtent(null);
const grat = geoGraticule().extent([
  [-130, 15],
  [45, 81],
]).step([10, 10]);
const graticule = geoPath(projection).digits(2)(grat()) ?? "";

writeFileSync(
  join(out, "land.ts"),
  `// Generated by scripts/build-geo.ts from Natural Earth (world-atlas). Do not edit.\n` +
    `export const LAND_ATLANTIC = ${JSON.stringify(atlantic)};\n` +
    `export const LAND_ISLES = ${JSON.stringify(isles)};\n` +
    `export const GRATICULE = ${JSON.stringify(graticule)};\n`,
);
console.log("atlantic", (atlantic.length / 1024).toFixed(0), "KB · isles", (isles.length / 1024).toFixed(0), "KB · graticule", (graticule.length / 1024).toFixed(1), "KB");
