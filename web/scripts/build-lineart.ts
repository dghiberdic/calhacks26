// Turn Blender Grease Pencil Line Art exports (public/renders/a321-*.svg) into path lists the
// blueprint can animate. Paths stay in the export's pixel space; a321-views.json maps them to metres.
// usage: npx tsx scripts/build-lineart.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "public/renders");
const views = JSON.parse(readFileSync(join(dir, "a321-views.json"), "utf8"));

function paths(file: string) {
  const svg = readFileSync(join(dir, file), "utf8");
  const out: { d: string; x: number }[] = [];
  for (const m of svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)) {
    const d = m[1];
    const first = d.match(/M\s*([-\d.]+)[ ,]([-\d.]+)/);
    // compress coordinates to 1 decimal to keep the bundle small
    const dd = d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10));
    out.push({ d: dd, x: first ? Number(first[1]) : 0 });
  }
  // nose → tail so a stagger plots like a pen moving aft
  return out.sort((a, b) => a.x - b.x).map((p) => p.d);
}

const side = paths("a321-side.svg");
const hero = paths("ns31-hero-lines.svg");
const top = paths("a321-top.svg");
const s = views.side;
const t = views.top;
const body =
  `// Generated by scripts/build-lineart.ts from Blender line art. Do not edit.\n` +
  `// side: metres = (px - nose) * mpp, height = (ground - py) * mpp; top: port is +y.\n` +
  `export const SIDE_LINES = ${JSON.stringify(side)};\n` +
  `export const SIDE_VIEW = ${JSON.stringify({ mpp: s.metres_per_pixel, noseX: s.nose_tip_px[0], groundY: s.ground_line_y_px })};\n` +
  `export const TOP_LINES = ${JSON.stringify(top)};\n` +
  `export const TOP_VIEW = ${JSON.stringify({ mpp: t.metres_per_pixel, noseX: t.nose_tip_px[0], centreY: t.centreline_y_px })};\n` +
  `// Pixel-aligned with public/renders/ns31-hero-render.webp (2560×1440, same camera).\n` +
  `export const HERO_LINES = ${JSON.stringify(hero)};\n`;
writeFileSync(join(process.cwd(), "src/data/geo/lineart.ts"), body);
console.log("side", side.length, "top", top.length, "hero", hero.length, (body.length / 1024).toFixed(0), "KB");
